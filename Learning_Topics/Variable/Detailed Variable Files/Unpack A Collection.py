# We first create a list of values, then unpack the values into separate variables..
animals = ['dog', 'cat', 'elephant']

# Now 3 variable has been created and the group value has been given to them
a, b, c = animals

# To get it, we can use print() and the variables inside it to extract the pack

print(a, b, c)

# Result => The group has been unpacked and the exact result was "dog cat elephant".
