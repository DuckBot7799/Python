# print() function is often used to output variables. For example -

a = "dog"
print(a)

# Result => "dog" as given value in "a" variable. print() function showed the variable's given value.

# We can print multiple variables together by separating them with commas inside print().

b = "mouse"
c = "elephant"
d = "dog"
print(b, c, d)

# Result => All 3 variables came in the output together, without writing output function for each variable, for example -

x = "rabbit"
y = "fox"
z = "eagle"

print(x)
print(y)
print(z)

# Result => The output still be the same, but without spending more time on each variable, we can put them in 1 output, making us to code a lil faster and easier.
